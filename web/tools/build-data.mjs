// Builds the real-data modules from open sources: node tools/build-data.mjs (npm run data).
//
//   BASt "Automatische Zählstellen" annual results -> src/data/real/motorways.js
//     Per motorway segment of the Germany level: median daily traffic, truck share and lanes of
//     the counting stations along it, the stations around Aachen for model validation, and
//     every motorway station's latest count (2020 or later) for the map layer, with attribution.
//   OpenStreetMap (Overpass API, ODbL) -> src/data/real/aachen-osm.js
//     Speed limit and lanes per direction of each street the Aachen model uses.
//
// If a source cannot be fetched, its module is left unchanged.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CITY_BY_ID, SEGMENTS } from "../src/data/germany-roads.js";
import { LINKS } from "../src/data/aachen.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src", "data", "real");
const UA = "MetaCity-build/0.1 (https://github.com/ETohidi/MetaCity)";
const BAST_URL = "https://www.bast.de/DE/Themen/Digitales/HF_1/Massnahmen/verkehrszaehlung/Daten/2023_1/Jawe2023.csv?view=renderTcDataExportCSVAlleJahre";
const BAST_PAGE = "https://www.bast.de/DE/Themen/Digitales/HF_1/Massnahmen/verkehrszaehlung/verkehrszaehlung.html";
// The main Overpass server is often busy; the mirror serves the same data.
const OVERPASS = ["https://overpass-api.de/api/interpreter", "https://overpass.kumi.systems/api/interpreter"];
const AACHEN_BBOX = "50.70,5.97,50.86,6.27";
const MIN_YEAR = 2020;

const num = (s) => {
  const t = String(s ?? "").trim().replace(/\./g, "").replace(",", ".");
  return t === "" ? null : Number(t);
};
const median = (xs) => {
  const v = xs.filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  return v.length ? (v.length % 2 ? v[(v.length - 1) / 2] : (v[v.length / 2 - 1] + v[v.length / 2]) / 2) : null;
};
const roundOrNull = (x, digits) => (x === null ? null : Math.round(x * 10 ** digits) / 10 ** digits);
const kmX = (lat) => 111.32 * Math.cos((lat * Math.PI) / 180);

/** Distance (km) of point p from segment a-b, and the position t along it (0..1). */
function project(p, a, b) {
  const kx = kmX((a.lat + b.lat) / 2);
  const ax = a.lon * kx, ay = a.lat * 110.57, bx = b.lon * kx, by = b.lat * 110.57, px = p.lon * kx, py = p.lat * 110.57;
  const dx = bx - ax, dy = by - ay;
  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)));
  return { t, km: Math.hypot(px - (ax + t * dx), py - (ay + t * dy)) };
}

function writeModule(file, header, name, data) {
  const body = `${header}\n// Generated by tools/build-data.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n\nexport const ${name} = ${JSON.stringify(data)};\n`;
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, file), body);
  console.log(`wrote src/data/real/${file}`);
}

// -- BASt ------------------------------------------------------------------------------------
async function bast() {
  // BASt's server refuses custom user agents, so this request uses Node's default one.
  const res = await fetch(BAST_URL);
  if (!res.ok) throw new Error(`BASt ${res.status}`);
  const text = new TextDecoder("iso-8859-15").decode(await res.arrayBuffer());
  const [head, ...lines] = text.split(/\r?\n/).filter(Boolean);
  const cols = head.split(";");
  const at = Object.fromEntries(cols.map((c, i) => [c, i]));
  // Latest year with a daily-traffic value, per station, motorways only.
  const latest = new Map();
  for (const line of lines) {
    const f = line.split(";").map((x) => x.trim());
    if (f[at.Str_Kl] !== "A") continue;
    const dtv = num(f[at.DTV_Kfz_MobisSo_Q]);
    if (!dtv) continue;
    const st = {
      id: f[at.DZ_Nr],
      name: f[at.DZ_Name],
      road: `A${f[at.Str_Nr]}`,
      year: Number(f[at.Jahr]),
      lat: Number(f[at.Koor_WGS84_N].replace(",", ".")),
      lon: Number(f[at.Koor_WGS84_E].replace(",", ".")),
      dtv,
      hgv: (num(f[at.pSV_MobisSo_Q]) ?? NaN) / 100,
      lanes: num(f[at.Anz_Fs_Q]),
    };
    const prev = latest.get(st.id);
    if (!prev || st.year > prev.year) latest.set(st.id, st);
  }
  // Only recent counts: a station last counted years ago says little about today's traffic.
  const stations = [...latest.values()].filter((s) => s.year >= MIN_YEAR);
  const year = Math.max(...stations.map((s) => s.year));
  const segments = {};
  for (const seg of SEGMENTS) {
    const a = CITY_BY_ID[seg.from];
    const b = CITY_BY_ID[seg.to];
    // Stations on the same road, close to the segment and not at the junctions at its ends
    // (those count traffic of the neighbouring segments too).
    const on = stations
      .filter((s) => s.road === seg.road)
      .map((s) => ({ s, ...project(s, a, b) }))
      .filter((x) => x.km < 10 && x.t > (a.border ? 0 : 0.04) && x.t < (b.border ? 1 : 0.92));
    if (!on.length) continue;
    segments[seg.id] = {
      aadt: Math.round(median(on.map((x) => x.s.dtv))),
      hgv: roundOrNull(median(on.map((x) => x.s.hgv).filter((h) => h > 0)), 3),
      lanes: Math.round(median(on.map((x) => x.s.lanes / 2).filter((l) => l >= 1)) ?? seg.lanes),
      stations: on.length,
      year: Math.max(...on.map((x) => x.s.year)),
      examples: on.slice(0, 3).map((x) => x.s.name),
    };
  }
  // Stations around Aachen, for checking the city model against real counts.
  const aachen = stations
    .filter((s) => s.lat > 50.68 && s.lat < 50.9 && s.lon > 5.95 && s.lon < 6.3)
    .map(({ id, name, road, year: y, lat, lon, dtv, hgv }) => ({ id, name, road, year: y, lat, lon, dtv, hgv: Math.round(hgv * 1000) / 1000 }));
  // Every station for the map layer, compact: [id, name, road, year, lat, lon, dtv, truck share].
  const all = stations.map((s) => [s.id, s.name, s.road, s.year, Math.round(s.lat * 1e4) / 1e4, Math.round(s.lon * 1e4) / 1e4, s.dtv, Number.isFinite(s.hgv) ? Math.round(s.hgv * 1000) / 1000 : null]);
  writeModule(
    "motorways.js",
    `// Motorway volumes from the BASt annual results of automatic counting stations\n// (Bundesanstalt für Straßenwesen, "Automatische Zählstellen", ${BAST_PAGE}).\n// Per segment of the Germany level, plus each motorway station's latest count (2020 or later).`,
    "MOTORWAYS",
    { source: "BASt, Automatische Zählstellen", url: BAST_PAGE, year, segments, aachen, stationFields: ["id", "name", "road", "year", "lat", "lon", "dtv", "hgv"], stations: all },
  );
  console.log(`BASt: ${stations.length} motorway stations, ${Object.keys(segments).length}/${SEGMENTS.length} segments matched, ${aachen.length} around Aachen`);
}

// -- OpenStreetMap ----------------------------------------------------------------------------
/** "Alleenring (Monheimsallee)" -> "Monheimsallee"; "Trierer Straße → Eifel" -> "Trierer Straße". */
const osmName = (name) => (name.match(/\(([^)]+)\)/)?.[1] ?? name.split(" → ")[0]).trim();

function wayKm(geom) {
  let km = 0;
  for (let i = 1; i < geom.length; i++) {
    const kx = kmX(geom[i].lat);
    km += Math.hypot((geom[i].lon - geom[i - 1].lon) * kx, (geom[i].lat - geom[i - 1].lat) * 110.57);
  }
  return km;
}

/** Lanes in one direction of travel. */
function lanesPerDirection(tags) {
  const lanes = Number(tags.lanes);
  if (tags.oneway === "yes" || tags.oneway === "-1") return Number.isFinite(lanes) ? lanes : 1;
  const fwd = Number(tags["lanes:forward"]);
  const bwd = Number(tags["lanes:backward"]);
  if (Number.isFinite(fwd) && Number.isFinite(bwd)) return (fwd + bwd) / 2;
  return Number.isFinite(lanes) ? lanes / 2 : 1;
}

async function osm() {
  const names = [...new Set(LINKS.filter((l) => l.cls !== "motorway").map((l) => osmName(l.name)))];
  const re = names.map((n) => n.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
  const query = `[out:json][timeout:90];way["highway"]["name"~"^(${re})$"](${AACHEN_BBOX});out tags geom;`;
  let data = null;
  for (const url of OVERPASS) {
    try {
      const res = await fetch(url, { method: "POST", headers: { "user-agent": UA, "content-type": "application/x-www-form-urlencoded" }, body: `data=${encodeURIComponent(query)}` });
      if (res.ok) {
        data = await res.json();
        break;
      }
      console.warn(`${url}: ${res.status}`);
    } catch (err) {
      console.warn(`${url}: ${err.message}`);
    }
  }
  if (!data) throw new Error("no Overpass server answered");
  const ways = data.elements.filter((w) => /^(motorway|trunk|primary|secondary|tertiary|unclassified|residential)/.test(w.tags.highway));
  const streets = {};
  for (const n of names) {
    const ws = ways.filter((w) => w.tags.name === n).map((w) => ({ km: wayKm(w.geometry), tags: w.tags }));
    if (!ws.length) continue;
    // Length-weighted typical values: the most common speed limit, the median lanes per direction.
    const speedKm = {};
    for (const w of ws) if (/^\d+$/.test(w.tags.maxspeed ?? "")) speedKm[w.tags.maxspeed] = (speedKm[w.tags.maxspeed] ?? 0) + w.km;
    const maxspeed = Number(Object.entries(speedKm).sort((x, y) => y[1] - x[1])[0]?.[0]) || null;
    const lanesWeighted = ws.flatMap((w) => Array(Math.max(1, Math.round(w.km * 20))).fill(lanesPerDirection(w.tags)));
    streets[n] = { maxspeed, lanes: Math.max(1, Math.round(median(lanesWeighted))), ways: ws.length, km: Math.round(ws.reduce((s, w) => s + w.km, 0) * 10) / 10 };
  }
  const links = {};
  for (const l of LINKS) {
    const s = streets[osmName(l.name)];
    if (s && l.cls !== "motorway") links[l.id] = { street: osmName(l.name), ...s };
  }
  writeModule(
    "aachen-osm.js",
    "// Speed limits and lanes of the Aachen model's streets, from OpenStreetMap\n// (© OpenStreetMap contributors, ODbL 1.0, https://www.openstreetmap.org/copyright).",
    "AACHEN_OSM",
    { source: "OpenStreetMap", licence: "ODbL 1.0", url: "https://www.openstreetmap.org/copyright", links },
  );
  console.log(`OSM: ${ways.length} ways, ${Object.keys(links).length}/${LINKS.filter((l) => l.cls !== "motorway").length} street links matched; no match: ${names.filter((n) => !streets[n]).join(", ") || "none"}`);
}

for (const [name, job] of [
  ["BASt", bast],
  ["OpenStreetMap", osm],
]) {
  try {
    await job();
  } catch (err) {
    console.warn(`${name} skipped, keeping the committed module: ${err.message}`);
  }
}
